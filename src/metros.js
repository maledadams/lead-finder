/**
 * The list the crawl walks, one city per state at a time.
 *
 * Not state by state, which is what the grouping above would give for free. A
 * crawl takes the least recently swept boxes first, so an alphabetical order
 * would spend its first weeks inside Alabama, Alaska and Arizona and reach
 * Wyoming next year. Round-robin means the first day already covers several
 * states and the whole country is sampled from the start, largest cities first
 * within each state.
 */
export const METROS = (() => {
  const states = Object.values(METROS_BY_STATE);
  const out = [];
  for (let i = 0; ; i++) {
    let added = false;
    for (const cities of states) {
      if (i < cities.length) { out.push(cities[i]); added = true; }
    }
    if (!added) return out;
  }
})();
