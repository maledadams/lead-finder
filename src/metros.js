// looking in Florida?" — and flattened at the bottom into the list the crawl
// actually walks.
//
// HOW A BOX IS SIZED. Each entry is a bounding box, not a point, and its size
// comes from the city's population: a small town gets about 9 km across, a large
// city about 22 km. Longitude is scaled by 1/cos(latitude), so a box in Anchorage
// covers the same ground as one in Miami instead of a thin sliver.
//
