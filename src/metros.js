// Overpass truncates its answer, which would quietly limit the whole city to
// whichever elements came back first. Nine boxes cover it and none truncate.
//
// WHERE THE NUMBERS COME FROM. Coordinates are derived from a public dataset of
// the ~1,000 largest US municipalities, plus 42 towns geocoded through OSM's own
// geocoder to fill out the states that dataset barely reaches — Alaska, Hawaii,
// Vermont, the Dakotas and so on. None of them were typed from memory, which is
// why there are no plausible-looking boxes sitting in the ocean.

